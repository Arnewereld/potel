export const docTexts: Record<Language, Record<DocKey, string>> = { nl, en }

export const languages: { id: Language; label: string }[] = [
  { id: 'nl', label: 'Nederlands' },
  { id: 'en', label: 'Engels' },
]

export const isEnglish = (lang?: Language | null) => lang === 'en'

// De tekst bij een sleutel in de taal van de klant, met de woorden tussen accolades ingevuld. In één keer, zodat wat er
// ingevuld wordt niet nog eens doorzocht wordt. Onbekende woorden blijven staan.
export function t(lang: Language | null | undefined, key: DocKey, vars?: Record<string, string | number>) {
  const text = docTexts[isEnglish(lang) ? 'en' : 'nl'][key]
  return vars ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : text
}

const locale = (lang?: Language | null) => (isEnglish(lang) ? 'en-GB' : 'nl-NL')
const euroFormats = {
  nl: new Intl.NumberFormat('nl-NL', { style: 'currency', currency: 'EUR' }),
  en: new Intl.NumberFormat('en-GB', { style: 'currency', currency: 'EUR' }),
}
const numFormats = {
  nl: new Intl.NumberFormat('nl-NL', { maximumFractionDigits: 2 }),
  en: new Intl.NumberFormat('en-GB', { maximumFractionDigits: 2 }),
}

// € 1.234,56 of €1,234.56.
export const docEuro = (lang: Language | null | undefined, n: number) => euroFormats[isEnglish(lang) ? 'en' : 'nl'].format(n || 0)

// 14 okt 2026 of 14 Oct 2026.
export const docDate = (lang: Language | null | undefined, s?: string | null) =>
  s ? parseDate(s).toLocaleDateString(locale(lang), { day: 'numeric', month: 'short', year: 'numeric' }) : '—'

// Een moment dat de server in UTC bewaart, zoals het tijdstip van akkoord.
export const docDateTime = (lang: Language | null | undefined, s: string) =>
  new Date(s.endsWith('Z') ? s : `${s}Z`).toLocaleString(locale(lang), { day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' })

export const docNum = (lang: Language | null | undefined, n: number) => numFormats[isEnglish(lang) ? 'en' : 'nl'].format(n || 0)

// Minuten als "7,5 u" of "7.5 h".
export const docHours = (lang: Language | null | undefined, minutes: number, digits = 1) =>
  `${(minutes / 60).toLocaleString(locale(lang), { maximumFractionDigits: digits })} ${isEnglish(lang) ? 'h' : 'u'}`

// De eenheden van Potel in het Engels, enkelvoud en meervoud. In het Nederlands blijft de eenheid zoals hij op de regel staat.
const englishUnits: Record<string, [string, string]> = {
  uur: ['hour', 'hours'], dag: ['day', 'days'], stuk: ['item', 'items'], km: ['km', 'km'], maand: ['month', 'months'], jaar: ['year', 'years'],
}
export function docUnit(lang: Language | null | undefined, unit: string, quantity: number) {
  const english = isEnglish(lang) ? englishUnits[unit.trim().toLowerCase()] : undefined
  return english ? english[Math.abs(quantity) === 1 ? 0 : 1] : unit
}

