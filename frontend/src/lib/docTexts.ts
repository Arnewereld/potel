// De naam van een factuur of offerte, zoals in de titel van het tabblad en dus als bestandsnaam van de PDF.
export function docTitle(lang: Language | null | undefined, kind: 'invoice' | 'credit' | 'quote', number: string | null | undefined, seller: string) {
  if (!seller.trim()) return `${t(lang, kind === 'invoice' ? 'invoice.title' : kind === 'credit' ? 'invoice.creditTitle' : 'quote.title')} ${number ?? ''}`.trim()
  if (!number) return t(lang, kind === 'invoice' ? 'doc.invoiceDraft' : kind === 'credit' ? 'doc.creditDraft' : 'doc.quoteDraft', { seller })
  return t(lang, kind === 'invoice' ? 'doc.invoice' : kind === 'credit' ? 'doc.credit' : 'doc.quote', { number, seller })
}
